def decrypt_body(body: bytearray) -> bytearray:
    assert len(body) >= 0x8C000
    out = bytearray(body[:0x8C000])
    for base in range(0, 0x8C000, 0x400):
        for mnem, disp, imm in MUTATORS:
            off = base + disp
            if off + 4 > len(out):
                continue
            val = struct.unpack_from('<I', out, off)[0]
            if mnem == 'add':
                val = (val + imm) & 0xFFFFFFFF
            elif mnem == 'sub':
                val = (val - imm) & 0xFFFFFFFF
            elif mnem == 'xor':
                val ^= imm
            elif mnem == 'not':
                val = (~val) & 0xFFFFFFFF
            struct.pack_into('<I', out, off, val)
    return out

def extract_from_pe(pe_path: Path) -> bytes:
    data = pe_path.read_bytes()
    e_lfanew = struct.unpack_from('<I', data, 0x3C)[0]
    num_sections = struct.unpack_from('<H', data, e_lfanew + 6)[0]
    coff_size = struct.unpack_from('<H', data, e_lfanew + 20)[0]
    sec_off = e_lfanew + 24 + coff_size
    for i in range(num_sections):
        off = sec_off + i * 40
        name = data[off:off+8].split(b'\0', 1)[0]
        if name == b'.reloc':
            vsize, vrva, rsize, rptr = struct.unpack_from('<IIII', data, off + 8)
            # body starts at first non-zero after reloc table end (sample-specific 0x3400)
            # Heuristic: skip leading reloc blocks then zeros
            sec = data[rptr:rptr+rsize]
            # find high-entropy region: after 0x3400 in this sample
            start = 0x3400
            body = bytearray(sec[start:start+0x8C000])
            return bytes(decrypt_body(body))
    raise SystemExit('no .reloc section')

